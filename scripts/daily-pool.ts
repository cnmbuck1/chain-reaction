// Builds the daily puzzle pool: a year of solver-checked variants of campaign boards,
// written to src/daily/pool.ts. Seeded, so the same seed always writes the same pool.
// Run with `npm run daily-pool`. Changing the pool after launch changes past and future
// dailies for everyone, so only append to it then.

import { writeFileSync } from 'node:fs';
import { applySpec, finishDaily, type DailySpec } from '../src/daily/transform';
import { DAILY_BASES, MIN_DAILY_GUESS_ODDS } from '../src/daily/rules';
import { checkLevel } from '../src/levels/check';
import { levels } from '../src/levels/index';

const POOL_SIZE = 365;
const TRIES_PER_DAY = 400;

/** mulberry32: a small seeded random number generator. */
function rng(seed: number) {
  return () => {
    seed = (seed + 0x6d2b79f5) | 0;
    let t = Math.imul(seed ^ (seed >>> 15), 1 | seed);
    t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t;
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}

const random = rng(20261029);
const int = (n: number) => Math.floor(random() * n);
function shuffle<T>(items: T[]): T[] {
  const out = [...items];
  for (let i = out.length - 1; i > 0; i--) {
    const j = int(i + 1);
    [out[i], out[j]] = [out[j]!, out[i]!];
  }
  return out;
}

const bases = levels.filter((l) => DAILY_BASES.includes(l.id));
const pool: DailySpec[] = [];
const seen = new Set<string>();
const accepted = new Map<string, number>();
let order = shuffle(bases);

for (let day = 0; pool.length < POOL_SIZE; day++) {
  if (day % order.length === 0) order = shuffle(bases);
  const base = order[day % order.length]!;
  const switches = base.nodes.filter((n) => n.type === 'switch');
  const gates = base.nodes.filter((n) => n.type === 'gate');
  for (let t = 0; t < TRIES_PER_DAY; t++) {
    const spec: DailySpec = {
      base: base.id,
      flips: int(1 << switches.length),
      needs: int(1 << gates.length),
      combine: int(1 << gates.length),
    };
    if (spec.flips === 0 && spec.needs === 0) continue;
    const key = JSON.stringify(spec);
    if (seen.has(key)) continue;
    seen.add(key);
    const level = finishDaily(applySpec(base, spec), '2026-10-29');
    if (!level) continue;
    const { errors, report } = checkLevel(level);
    if (errors.length > 0 || (report?.guessOdds ?? 0) < MIN_DAILY_GUESS_ODDS) continue;
    pool.push(spec);
    accepted.set(base.id, (accepted.get(base.id) ?? 0) + 1);
    break;
  }
}

const rows = pool.map((s) => `  ['${s.base}', ${s.flips}, ${s.needs}, ${s.combine}],`);
writeFileSync(
  'src/daily/pool.ts',
  `// Generated by scripts/daily-pool.ts. Do not edit by hand; after launch, only append.
// Each row: base level, start flips, gate need flips, AND/OR swaps.

import type { DailySpec } from './transform';

type Row = readonly [string, number, number, number];

const ROWS: readonly Row[] = [
${rows.join('\n')}
];

export const DAILY_POOL: readonly DailySpec[] = ROWS.map(([base, flips, needs, combine]) => ({
  base,
  flips,
  needs,
  combine,
}));
`,
);
console.log(`Wrote ${pool.length} dailies.`);
for (const b of bases) console.log(`  ${b.id}  ${accepted.get(b.id) ?? 0}`);
